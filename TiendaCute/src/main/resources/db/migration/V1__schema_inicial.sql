-- V1__schema_inicial.sql
-- Esquema inicial de TiendaCute. Baseline para Flyway.
-- Todas las tablas usan IF NOT EXISTS para coexistir con ddl-auto=update.

CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    rol_usuario VARCHAR(50) NOT NULL,
    activo_usuario BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categorias (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR(255) NOT NULL,
    creado_en TIMESTAMP
);

CREATE TABLE IF NOT EXISTS productos (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_producto VARCHAR(255) NOT NULL,
    codigo_producto VARCHAR(45) NOT NULL UNIQUE,
    precio_compra_producto DECIMAL(10,2) NOT NULL DEFAULT 0,
    precio_venta_producto DECIMAL(10,2) NOT NULL DEFAULT 0,
    stock_actual_producto INT NOT NULL DEFAULT 0,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP,
    categoria_id BIGINT NOT NULL,
    CONSTRAINT fk_productos_categoria FOREIGN KEY (categoria_id) REFERENCES categorias(id_categoria)
);

CREATE TABLE IF NOT EXISTS clientes (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut_cliente VARCHAR(12),
    nombre VARCHAR(255),
    razon_social_cliente VARCHAR(255),
    giro_cliente VARCHAR(255),
    direccion_cliente VARCHAR(255),
    comuna_cliente VARCHAR(100),
    ciudad_cliente VARCHAR(100),
    email_cliente VARCHAR(255),
    telefono_cliente VARCHAR(50),
    creado_en TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ventas (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_venta TIMESTAMP,
    total_neto DECIMAL(10,2) NOT NULL DEFAULT 0,
    iva DECIMAL(10,2) NOT NULL DEFAULT 0,
    total DECIMAL(10,2) NOT NULL DEFAULT 0,
    tipo_documento VARCHAR(20) NOT NULL DEFAULT '',
    estado_venta VARCHAR(20) NOT NULL DEFAULT '',
    creado_en TIMESTAMP,
    usuario_id BIGINT NOT NULL,
    cliente_id BIGINT,
    monto_pagado DECIMAL(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT fk_ventas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id_usuario),
    CONSTRAINT fk_ventas_cliente FOREIGN KEY (cliente_id) REFERENCES clientes(id_cliente)
);

CREATE TABLE IF NOT EXISTS detalle_ventas (
    id_detalle_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad INT NOT NULL DEFAULT 0,
    precio_unitario DECIMAL(10,2) NOT NULL DEFAULT 0,
    subtotal DECIMAL(10,2) NOT NULL DEFAULT 0,
    venta_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    CONSTRAINT fk_detalle_ventas_venta FOREIGN KEY (venta_id) REFERENCES ventas(id_venta),
    CONSTRAINT fk_detalle_ventas_producto FOREIGN KEY (producto_id) REFERENCES productos(id_producto)
);

CREATE TABLE IF NOT EXISTS pagos (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metodo_pago VARCHAR(50) NOT NULL DEFAULT '',
    monto_pago DECIMAL(10,2) NOT NULL DEFAULT 0,
    referencia VARCHAR(255),
    creado_en TIMESTAMP,
    venta_id BIGINT NOT NULL,
    CONSTRAINT fk_pagos_venta FOREIGN KEY (venta_id) REFERENCES ventas(id_venta)
);

CREATE TABLE IF NOT EXISTS documentos_tributarios (
    id_documento_tributario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL DEFAULT '',
    folio INT NOT NULL DEFAULT 0,
    estado_sii VARCHAR(20) NOT NULL DEFAULT '',
    xml TEXT,
    track_id VARCHAR(100),
    fecha_envio TIMESTAMP,
    venta_id BIGINT NOT NULL,
    CONSTRAINT fk_documentos_tributarios_venta FOREIGN KEY (venta_id) REFERENCES ventas(id_venta)
);

CREATE TABLE IF NOT EXISTS cajas (
    id_caja BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_apertura TIMESTAMP,
    fecha_cierre TIMESTAMP,
    monto_inicial DECIMAL(10,2) NOT NULL DEFAULT 0,
    monto_final DECIMAL(10,2),
    estado_caja VARCHAR(20) NOT NULL DEFAULT '',
    usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_cajas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS movimientos_caja (
    id_movimiento_caja BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_movimiento VARCHAR(20) NOT NULL DEFAULT '',
    monto DECIMAL(10,2) NOT NULL DEFAULT 0,
    concepto VARCHAR(255) NOT NULL DEFAULT '',
    referencia_tipo VARCHAR(20),
    referencia_id BIGINT,
    fecha_movimiento TIMESTAMP,
    caja_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_movimientos_caja_caja FOREIGN KEY (caja_id) REFERENCES cajas(id_caja),
    CONSTRAINT fk_movimientos_caja_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS movimientos_stock (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_movimiento VARCHAR(45) NOT NULL DEFAULT '',
    cantidad_movimiento INT NOT NULL DEFAULT 0,
    motivo_movimiento VARCHAR(45) NOT NULL DEFAULT '',
    creado_en TIMESTAMP,
    producto_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_movimientos_stock_producto FOREIGN KEY (producto_id) REFERENCES productos(id_producto),
    CONSTRAINT fk_movimientos_stock_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id_usuario)
);
